#!/usr/bin/env python3
"""Export the decoder's exact SpinQuant bases for C++ hosts (no Torch dependency)."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "pytorch/spinquant/spinquant_inference/utils/hadamard_utils.py"
OUTPUT = ROOT / "tests/regression/vector_common/spinquant_hadamard.h"


def bases():
    tree = ast.parse(SOURCE.read_text())
    result = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in ("get_had28", "get_had172"):
            size = int(node.name.removeprefix("get_had"))
            value = next(n.value for n in node.body if isinstance(n, ast.Return))
            matrix = ast.literal_eval(value.args[0])
            assert len(matrix) == size and all(len(row) == size for row in matrix)
            assert all(x in (-1, 1) for row in matrix for x in row)
            result[size] = matrix
    assert set(result) == {28, 172}
    return result


def render():
    lines = ["// Generated by tools/workload/export_spinquant_hadamard.py; do not edit.",
             "// Source: pytorch/spinquant/spinquant_inference/utils/hadamard_utils.py",
             "#pragma once", "#include <cstdint>", "#include <vector>", "",
             "namespace spinquant_hadamard {"]
    for size, matrix in bases().items():
        bits = [int(x < 0) for row in matrix for x in row]
        encoded = ''.join(format(sum(bits[i+j] << j for j in range(4)), 'x')
                          for i in range(0, len(bits), 4))
        lines.append(f"static constexpr char signs_{size}[] =")
        lines.extend(f'    "{encoded[i:i+86]}"' for i in range(0, len(encoded), 86))
        lines[-1] += ';'
    lines += ["", "// Return FP16 +/-1 in the decoder's row-major basis orientation.",
              "inline bool fill(std::vector<uint16_t>& matrix, uint32_t size) {",
              "  if (size == 1) { matrix.assign(1, 0x3c00u); return true; }",
              "  const char* signs = size == 28 ? signs_28 : size == 172 ? signs_172 : nullptr;",
              "  if (!signs) return false;",
              "  matrix.resize(size * size);",
              "  for (uint32_t i = 0; i < size * size; ++i) {",
              "    const char c = signs[i / 4];",
              "    const unsigned bits = c <= '9' ? c - '0' : c - 'a' + 10;",
              "    matrix[i] = ((bits >> (i % 4)) & 1u) ? 0xbc00u : 0x3c00u;",
              "  }", "  return true;", "}", "} // namespace spinquant_hadamard", ""]
    return '\n'.join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("SpinQuant C++ bases are stale; run this script without --check")
    else:
        OUTPUT.write_text(content)
